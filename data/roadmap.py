def get_day_by_number(day_num: int):
    """Fetches a single day dictionary from ROADMAP_DAYS by day number (1-35)."""
    for day in ROADMAP_DAYS:
        if day["day"] == day_num:
            return day
    return None


def get_days_by_phase(phase_num: int):
    """Returns all days belonging to a specific phase (1-5)."""
    return [d for d in ROADMAP_DAYS if d["phase"] == phase_num]


def get_total_roadmap_days() -> int:
    """Returns the total number of roadmap days (35)."""
    return len(ROADMAP_DAYS)
